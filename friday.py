import pandas as pd

def analyze_football_data(df):
    """
    פונקציה שמנתחת נתוני כדורגל מתוך DataFrame של pandas.

    פרמטרים:
        df (pd.DataFrame): טבלת נתונים עם עמודות רלוונטיות, לדוג' ['קבוצה', 'שערים', 'בעיטות', 'ניצחונות', 'הפסדים']

    מדפיסה:
        ממוצעי שערים, בעיטות, יחס ניצחונות/הפסדים, ושחקן/קבוצה מצטיינים.
    """

    print("---- ניתוח נתוני כדורגל ----")

    if 'קבוצה' in df.columns:
        print(f"מספר קבוצות: {df['קבוצה'].nunique()}")
        print(f"הקבוצות: {df['קבוצה'].unique()}")
    if 'שערים' in df.columns:
        print(f"ממוצע שערים: {df['שערים'].mean():.2f}")
        print(f"קבוצה עם הכי הרבה שערים: {df.loc[df['שערים'].idxmax()]['קבוצה']} ({df['שערים'].max()})")
    if 'בעיטות' in df.columns:
        print(f"ממוצע בעיטות: {df['בעיטות'].mean():.2f}")
    if 'ניצחונות' in df.columns and 'הפסדים' in df.columns:
        df['יחס ניצחון/הפסד'] = df['ניצחונות'] / df['הפסדים'].replace(0, 1)
        print(f"קבוצה עם יחס ניצחון/הפסד גבוה: {df.loc[df['יחס ניצחון/הפסד'].idxmax()]['קבוצה']} ({df['יחס ניצחון/הפסד'].max():.2f})")

    print("----------------------------")

# דוגמה לשימוש:
# נתוני דמו
data = {
    'קבוצה': ['מכבי תל אביב', 'הפועל תל אביב', 'בית"ר ירושלים'],
    'שערים': [45, 32, 28],
    'בעיטות': [120, 110, 98],
    'ניצחונות': [18, 11, 8],
    'הפסדים': [3, 9, 11]
}
df = pd.DataFrame(data)
